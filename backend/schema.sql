CREATE TABLE IF NOT EXISTS mailbox (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  message TEXT NOT NULL,
  date INT NOT NULL,
  approval INT DEFAULT 0,
  IsRead INT
);


CREATE TABLE IF NOT EXISTS events (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL,
  date DATE NOT NULL,
  doors DATETIME,
  begin DATETIME,
  place TEXT NOT NULL,
  city TEXT NOT NULL,
  coordinates TEXT,
  link TEXT DEFAULT '',
  pic BLOB,
  hash TEXT NOT NULL
);
